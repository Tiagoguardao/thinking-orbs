import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

type NumberMap = Record<string, number>;
type Spec = {
  specVersion: string;
  enums: { states: string[]; sizes: number[] };
  stateToMode: Record<string, string>;
  baseProfiles: Record<string, NumberMap>;
  presets: Record<string, Record<string, { speed: number; count: number; size: number; extra?: NumberMap }>>;
  scaling: {
    countPairs: [string, string][];
    countKeys: string[];
    iconDensityKeys: string[];
    radiusKeys: string[];
  };
};

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const specPath = resolve(root, 'spec/orbs-spec.json');
const goldenPath = resolve(root, 'spec/orbs-golden.json');
const outputPath = resolve(
  root,
  'ports/ios/ThinkingOrbsKit/Sources/ThinkingOrbsKit/Generated/OrbSpec.swift'
);
const fixturePath = resolve(
  root,
  'ports/ios/ThinkingOrbsKit/Tests/ThinkingOrbsKitTests/Fixtures/orbs-golden.json'
);
const spec = JSON.parse(readFileSync(specPath, 'utf8')) as Spec;

function resolveOptions(mode: string, size: number): { speed: number; options: NumberMap } {
  const preset = spec.presets[mode][String(size)];
  const options: NumberMap = { ...spec.baseProfiles[mode] };
  const paired = new Set<string>();
  const rootCount = Math.sqrt(preset.count);

  if (preset.count !== 1) {
    for (const [first, second] of spec.scaling.countPairs) {
      if (options[first] == null || options[second] == null || paired.has(first) || paired.has(second)) continue;
      options[first] = Math.max(2, Math.round(options[first] * rootCount));
      options[second] = Math.max(2, Math.round(options[second] * rootCount));
      paired.add(first);
      paired.add(second);
    }
    for (const key of spec.scaling.countKeys) {
      if (options[key] == null || options[key] === 0 || paired.has(key)) continue;
      options[key] = Math.max(1, Math.round(options[key] * preset.count));
    }
    for (const key of spec.scaling.iconDensityKeys) {
      if (options[key] != null) options[key] = Math.max(0.02, options[key] * preset.count);
    }
  }

  if (preset.size !== 1) {
    for (const key of spec.scaling.radiusKeys) {
      if (options[key] != null) options[key] *= preset.size;
    }
    options.rSizeMul = (options.rSizeMul ?? 1) * preset.size;
  }
  Object.assign(options, preset.extra ?? {});
  return { speed: preset.speed, options };
}

const cases: string[] = [];
for (const state of spec.enums.states) {
  const mode = spec.stateToMode[state];
  for (const size of spec.enums.sizes) {
    const resolved = resolveOptions(mode, size);
    const options = Object.entries(resolved.options)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([key, value]) => `                "${key}": ${value}`)
      .join(',\n');
    cases.push(`        case (.${state}, .px${size}):
            OrbGeneratedPreset(
                mode: .${mode},
                speed: ${resolved.speed},
                options: [
${options}
                ]
            )`);
  }
}

const swift = `// Generated by scripts/codegen-swift.ts from spec/orbs-spec.json.
// Do not edit by hand. Spec version: ${spec.specVersion}.

enum OrbMode: String, Sendable {
${Object.values(spec.stateToMode)
  .map((mode) => `    case ${mode}`)
  .join('\n')}
}

struct OrbGeneratedPreset: Sendable {
    let mode: OrbMode
    let speed: Double
    let options: [String: Double]
}

enum OrbSpec {
    static let version = "${spec.specVersion}"

    static func preset(
        state: ThinkingOrbState,
        size: ThinkingOrbSize
    ) -> OrbGeneratedPreset {
        switch (state, size) {
${cases.join('\n')}
        }
    }
}
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, swift);
mkdirSync(dirname(fixturePath), { recursive: true });
writeFileSync(fixturePath, readFileSync(goldenPath));
console.log(`Generated ${outputPath}`);
console.log(`Copied ${fixturePath}`);
